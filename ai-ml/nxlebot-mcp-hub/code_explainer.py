"""
Nxlebot Code Explainer & Course Generator
Generate interactive HTML course from any codebase using Ollama (Qwen2.5)
"""

import os
import sys
import json
import httpx
import argparse
from pathlib import Path

# Config
OLLAMA_URL = "http://localhost:11434/api/generate"
MODEL = "qwen2.5:7b"
OUTPUT_DIR = Path("generated_courses")
OUTPUT_DIR.mkdir(exist_ok=True)

EXTENSIONS = [".py", ".js", ".ts", ".md", ".sh"]
IGNORE_FOLDERS = [".git", "venv", "node_modules", "__pycache__"]

def get_ollama_response(prompt):
    """Send prompt to Ollama and get response"""
    try:
        response = httpx.post(OLLAMA_URL, json={
            "model": MODEL,
            "prompt": prompt,
            "stream": False
        }, timeout=60)
        return response.json().get("response", "")
    except Exception as e:
        return f"⚠️ Ollama Error: {str(e)}"

def scan_codebase(target_path):
    """Scan directory for relevant files"""
    files = []
    target = Path(target_path)
    
    if not target.exists():
        print(f"❌ Path not found: {target}")
        sys.exit(1)

    for root, dirs, filenames in os.walk(target):
        # Skip ignored folders
        dirs[:] = [d for d in dirs if d not in IGNORE_FOLDERS]
        
        for filename in filenames:
            if any(filename.endswith(ext) for ext in EXTENSIONS):
                file_path = Path(root) / filename
                rel_path = file_path.relative_to(target)
                files.append(str(rel_path))
                
    return files

def explain_file(target_path, file_relative_path):
    """Ask Ollama to explain a file in plain English + Metaphors"""
    full_path = Path(target_path) / file_relative_path
    
    try:
        with open(full_path, "r", encoding="utf-8", errors="ignore") as f:
            code = f.read()[:5000]  # Limit to first 5000 chars to save time
    except:
        return "⚠️ Could not read file."

    prompt = f"""
    You are Nxlebot, a King Hacker AI. Explain this code file in simple terms.
    
    File: {file_relative_path}
    Code:
    ```
    {code}
    ```

    Output format strictly in JSON:
    {{
        "summary": "1 sentence what this file does",
        "metaphor": "A real-world analogy (e.g., 'This is like a bouncer checking IDs')",
        "key_points": ["point 1", "point 2"],
        "plain_english": "Simple explanation for a non-coder"
    }}
    """
    
    response = get_ollama_response(prompt)
    
    # Try to parse JSON from response
    try:
        # Find JSON block if wrapped in markdown
        if "```json" in response:
            response = response.split("```json")[1].split("```")[0].strip()
        elif "```" in response:
            response = response.split("```")[1].split("```")[0].strip()
            
        return json.loads(response)
    except:
        return {
            "summary": "Error parsing AI response",
            "metaphor": "AI got confused",
            "key_points": [response[:100]],
            "plain_english": response
        }

def generate_html(project_name, explanations):
    """Generate Single HTML Course File"""
    html_content = f"""
    <!DOCTYPE html>
    <html lang="en">
    <head>
        <meta charset="UTF-8">
        <meta name="viewport" content="width=device-width, initial-scale=1.0">
        <title>Nxlebot Course: {project_name}</title>
        <style>
            :root {{ --bg: #0f172a; --card: #1e293b; --text: #f8fafc; --accent: #38bdf8; }}
            body {{ background: var(--bg); color: var(--text); font-family: 'Segoe UI', sans-serif; margin: 0; padding: 20px; }}
            .container {{ max-width: 900px; margin: 0 auto; }}
            h1 {{ color: var(--accent); border-bottom: 2px solid var(--accent); padding-bottom: 10px; }}
            .card {{ background: var(--card); padding: 20px; margin-bottom: 20px; border-radius: 12px; box-shadow: 0 4px 6px rgba(0,0,0,0.3); }}
            .file-name {{ color: #94a3b8; font-family: monospace; font-size: 0.9em; }}
            .metaphor {{ color: #fbbf24; font-style: italic; border-left: 3px solid #fbbf24; padding-left: 10px; margin: 10px 0; }}
            .summary {{ font-weight: bold; font-size: 1.1em; }}
        </style>
    </head>
    <body>
        <div class="container">
            <h1>👑 Nxlebot Code Course: {project_name}</h1>
            <p>Generated by Nxlebot AI using Ollama (Qwen2.5)</p>
    """

    for item in explanations:
        data = item['data']
        html_content += f"""
        <div class="card">
            <div class="file-name">📄 {item['file']}</div>
            <div class="summary">{data.get('summary', 'No summary')}</div>
            <div class="metaphor">💡 Metaphor: {data.get('metaphor', 'No metaphor')}</div>
            <p>{data.get('plain_english', 'No explanation')}</p>
        </div>
        """

    html_content += """
        </div>
    </body>
    </html>
    """
    
    return html_content

def main():
    parser = argparse.ArgumentParser(description="Nxlebot Code Explainer")
    parser.add_argument("target", help="Path to codebase folder")
    parser.add_argument("--output", "-o", default="index.html", help="Output filename")
    args = parser.parse_args()

    print(f"🚀 Scanning codebase: {args.target}")
    files = scan_codebase(args.target)
    print(f"📂 Found {len(files)} relevant files")

    explanations = []
    project_name = Path(args.target).name
    
    for i, file_path in enumerate(files):
        print(f" Explaining [{i+1}/{len(files)}]: {file_path}")
        data = explain_file(args.target, file_path)
        explanations.append({"file": file_path, "data": data})

    print("🎨 Generating HTML Course...")
    html = generate_html(project_name, explanations)
    
    output_path = OUTPUT_DIR / args.output
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(html)

    print(f"✅ Done! Course saved to: {output_path}")
    print(f"🌐 Open it in your browser to start learning.")

if __name__ in "__main__":
    main()
